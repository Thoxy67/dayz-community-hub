//! The parity catalog: every user-visible feature of the Svelte interface (`apps/gui/src`),
//! one entry each, as five inventory agents listed them view by view (M0.7).
//!
//! A [`Kind::Command`] feature names the command id that will carry it in the command
//! registry (`commands.rs`); once that registry exists, a command feature also counts as done
//! when its id is registered. A [`Kind::Display`] feature is done when its `done` flag is set,
//! which a screenshot comparison with `var/reference/<view>.png` justifies.
//!
//! `docs/parity-checklist.md` is generated from this list (`cargo xtask parity`, or the ignored
//! `write_checklist` test); the `parity_floor` test pins a number of done features that only
//! rises.

/// How a feature is carried in the egui window.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// An action a button, shortcut, the palette, a pad or the control channel triggers:
    /// the command id it is registered under.
    Command(&'static str),
    /// Something shown: a layout, a state, a figure, a behaviour without its own command.
    Display,
}

/// One feature of the Svelte interface.
#[derive(Debug, Clone, Copy)]
pub struct Feature {
    /// Unique id, `<view>.<area>.<thing>`.
    pub id: &'static str,
    /// The view (or `shell`, `setup`) it belongs to.
    pub view: &'static str,
    /// What the Svelte interface does, in enough detail to port it.
    pub what: &'static str,
    pub kind: Kind,
    /// Ported and checked against the reference.
    pub done: bool,
}

