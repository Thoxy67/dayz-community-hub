/// Done features; only rises.
pub const FLOOR: usize = 714;

/// Whether a feature counts as done.
pub fn is_done(feature: &Feature) -> bool {
    feature.done || matches!(feature.kind, Kind::Command(id) if crate::commands::registered(id))
}

/// `(done, total)` over the whole catalog.
pub fn counts() -> (usize, usize) {
    let done = CATALOG.iter().filter(|f| is_done(f)).count();
    (done, CATALOG.len())
}

/// `(view, done, total)` for every view of [`VIEWS`], then any view the list does not name.
pub fn view_counts() -> Vec<(&'static str, usize, usize)> {
    let mut views: Vec<&'static str> = VIEWS.to_vec();
    for f in CATALOG {
        if !views.contains(&f.view) {
            views.push(f.view);
        }
    }
    views
        .into_iter()
        .map(|v| {
            let of_view = CATALOG.iter().filter(|f| f.view == v);
            let total = of_view.clone().count();
            let done = of_view.filter(|f| is_done(f)).count();
            (v, done, total)
        })
        .filter(|(_, _, total)| *total > 0)
        .collect()
}

/// The checklist markdown (`docs/parity-checklist.md`).
pub fn checklist_markdown() -> String {
    fn cell(s: &str) -> String {
        s.replace('|', "\\|").replace('\n', " ")
    }
    let (done, total) = counts();
    let pct = |d: usize, t: usize| {
        if t == 0 {
            0.0
        } else {
            d as f64 * 100.0 / t as f64
        }
    };
    let mut out = String::new();
    out.push_str("# Svelte → egui parity checklist\n\n");
    out.push_str(
        "Generated from `apps/desktop/src/catalog.rs` (`cargo xtask parity`, or \
         `cargo test -p dayz-community-hub-egui catalog::tests::write_checklist -- --ignored`). \
         Do not edit by hand.\n\n",
    );
    out.push_str(&format!(
        "**{done} of {total} features done ({:.1}%).**\n\n",
        pct(done, total)
    ));
    out.push_str("| View | Done | Total | % |\n|---|---:|---:|---:|\n");
    let views = view_counts();
    for (v, d, t) in &views {
        out.push_str(&format!("| {v} | {d} | {t} | {:.0}% |\n", pct(*d, *t)));
    }
    for (v, d, t) in &views {
        out.push_str(&format!("\n## {v} ({d}/{t})\n\n"));
        out.push_str("| id | what | kind / command | |\n|---|---|---|---|\n");
        for f in CATALOG.iter().filter(|f| f.view == *v) {
            let kind = match f.kind {
                Kind::Command(c) => format!("`{c}`"),
                Kind::Display => "display".to_string(),
            };
            let mark = if is_done(f) { "✅" } else { "⬜" };
            out.push_str(&format!(
                "| `{}` | {} | {} | {} |\n",
                f.id,
                cell(f.what),
                kind,
                mark
            ));
        }
    }
    out
}

